function init(){

    document.querySelector(".phrase1").addEventListener("mouseover", survolPhrase);
    document.querySelector(".phrase2").addEventListener("mouseover", survolPhrase);
    document.querySelector(".phrase3").addEventListener("mouseover", survolPhrase);

    document.querySelector(".phrase1").addEventListener("mouseout", finSurvolPhrase);
    document.querySelector(".phrase2").addEventListener("mouseout", finSurvolPhrase);
    document.querySelector(".phrase3").addEventListener("mouseout", finSurvolPhrase);

}

