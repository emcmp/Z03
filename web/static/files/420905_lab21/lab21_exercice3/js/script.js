zStop = false;

function nombreAleatoire(min, max){

    if(zStop) return;

    zStop = true;
    let r = min + Math.floor(Math.random() * (max - min + 1));
    document.querySelector(".de").classList.add("rotation");
    setTimeout(function(){document.querySelector(".de").textContent = r}, 150);
    setTimeout(function(){document.querySelector(".de").classList.remove("rotation"); zStop = false; }, 300);

}